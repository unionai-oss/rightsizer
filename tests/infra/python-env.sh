#!/usr/bin/env bash
# Repo-root .venv (Python 3.12, uv) for integration tests: pytest, flyte, ray, ...
#
#   python-env.sh up         create/sync .venv from tests/infra/requirements-it.txt (pinned)
#   python-env.sh relock     re-resolve the unpinned set below and rewrite requirements-it.txt
#   python-env.sh status     print interpreter + key package versions
#   python-env.sh down       delete .venv
set -euo pipefail
RSZ_COMPONENT=python-env
# shellcheck source=common/common.sh
source "$(dirname "${BASH_SOURCE[0]}")/common/common.sh"

VENV="${RSZ_IT_VENV:-${REPO_ROOT}/.venv}"
PY_VERSION="${RSZ_IT_PYTHON:-3.12}"
LOCK="${INFRA_DIR}/requirements-it.txt"
# Unpinned top-level set; `relock` resolves it and writes the exact pins to $LOCK.
TOP_LEVEL=(
  pytest pytest-asyncio hypothesis maturin
  "flyte==2.13.*"          # match the host CLI's SDK (flyte --version)
  "ray[default]"
  fsspec s3fs pyarrow numpy pandas scikit-learn lightgbm
)

ensure_venv() {
  need uv
  if [[ ! -x "$VENV/bin/python" ]]; then
    log "creating $VENV (Python ${PY_VERSION})"
    uv venv --python "$PY_VERSION" "$VENV" >/dev/null
  fi
  local v; v="$("$VENV/bin/python" -c 'import sys; print("%d.%d" % sys.version_info[:2])')"
  [[ "$v" == "$PY_VERSION" ]] || die "$VENV is Python $v, expected ${PY_VERSION}; run: python-env.sh down && python-env.sh up"
}

cmd_up() {
  ensure_venv
  if [[ -f "$LOCK" ]]; then
    log "syncing $VENV from $(basename "$LOCK")"
    # Additive install (not `uv pip sync`) so packages other tooling put in the
    # shared .venv, e.g. a `maturin develop` build of rightsizer, are kept.
    uv pip install --python "$VENV/bin/python" -r "$LOCK"
  else
    cmd_relock
  fi
  ok "venv ready: source ${VENV}/bin/activate"
}

cmd_relock() {
  ensure_venv
  log "resolving: ${TOP_LEVEL[*]}"
  uv pip install --python "$VENV/bin/python" "${TOP_LEVEL[@]}"
  {
    echo "# Pinned integration-test environment. Generated by tests/infra/python-env.sh relock"
    echo "# on $(date -u +%Y-%m-%d) for Python ${PY_VERSION} ($(uname -s)/$(uname -m))."
    echo "# Top-level: ${TOP_LEVEL[*]}"
    uv pip freeze --python "$VENV/bin/python" --exclude-editable
  } >"$LOCK"
  ok "wrote $LOCK ($(grep -vc '^#' "$LOCK") pins)"
}

cmd_status() {
  if [[ ! -x "$VENV/bin/python" ]]; then echo "python-env: ${VENV}: DOWN"; return 0; fi
  echo "python-env: ${VENV}: UP ($("$VENV/bin/python" --version))"
  "$VENV/bin/python" - <<'EOF'
from importlib.metadata import version, PackageNotFoundError
names = ["flyte", "ray", "pytest", "hypothesis", "maturin", "pyarrow", "pandas", "lightgbm", "scikit-learn"]
out = []
for n in names:
    try:
        out.append(f"{n}=={version(n)}")
    except PackageNotFoundError:
        out.append(f"{n}=MISSING")
print("  " + " ".join(out))
EOF
}

cmd_down() {
  [[ -d "$VENV" ]] && rm -rf "$VENV" && log "removed $VENV"
  ok "venv down"
}

case "${1:-}" in
  up) cmd_up ;;
  relock) cmd_relock ;;
  status) cmd_status ;;
  down) cmd_down ;;
  *) usage_and_exit "usage: python-env.sh up|relock|status|down" ;;
esac
